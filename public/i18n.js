// Exported so a test can hold the two books side by side: a key present in one
// and missing from the other is how a screen ends up half-translated.
export const BOOKS = { en: EN, ja: JA };

let current = DEFAULT_LANG;

export function setLang(code) {
  current = BOOKS[code] ? code : DEFAULT_LANG;
  return current;
}

export function getLang() {
  return current;
}

// The name of the current language, in English, for the closing line that asks
// a session to answer in it — the rest of that message is English too.
export function langNameInEnglish(code = current) {
  return code === 'ja' ? 'Japanese' : 'English';
}

export function t(key, vars) {
  const book = BOOKS[current] || EN;
  let text = book[key];
  if (text === undefined) text = EN[key];
  if (text === undefined) return key;          // a visible fault beats a blank
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole
  ));
}

// Walks the page and fills in everything marked with a key. Called once at
// startup and again whenever the language changes, so no screen has to be
// rebuilt by hand to follow a switch.
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'));
  }
  for (const el of root.querySelectorAll('[data-i18n-html]')) {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  }
  for (const el of root.querySelectorAll('[data-i18n-ph]')) {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  }
  for (const el of root.querySelectorAll('[data-i18n-label]')) {
    const text = t(el.getAttribute('data-i18n-label'));
    el.setAttribute('aria-label', text);
    if (el.hasAttribute('title')) el.setAttribute('title', text);
  }
  if (root === document) {
    document.documentElement.lang = current;
    document.title = t('app.title');
  }
}
